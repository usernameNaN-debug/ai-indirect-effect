const escapeHtml = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');

export function cite(id, label = references[id].citation) {
  return `<a class="reference-link" data-reference="${escapeHtml(id)}" href="${escapeHtml(references[id].url)}">${escapeHtml(label)}</a>`;
}

export function bibliography(ids = Object.keys(references)) {
  return ids.map(id => {
    const r = references[id];
    const location = r.pages ? `, ${r.pages}` : r.articleNumber ? `, ${r.articleNumber}` : '';
    return `<span class="source-entry" id="source-${escapeHtml(id)}">${escapeHtml(r.authors.join(', '))} (${r.year}). ${cite(id, r.title)}. <em>${escapeHtml(r.venue)}${escapeHtml(location)}</em>. ${escapeHtml(r.annotation)}</span>`;
  });
}
